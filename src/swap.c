#include "push_swap.h"

void	swap(t_stack **L)
{
	t_stack	*tmp;

	if (!*L || !(*L)->next)
		return ;
	tmp = (*L)->next;
	(*L)->next = tmp->next;
	tmp->next = *L;
	*L = tmp;
}
